const assert=require('node:assert/strict');
const Clock=require('../android/app/src/main/assets/playback.js');
const events=[{at:0,hex:'on'},{at:.2,hex:'off'},{at:.4,hex:'next'},{at:.6,hex:'release'}];
let c=new Clock(events,0);
assert.deepEqual(c.step(0,0),[events[0]]);
assert.deepEqual(c.step(200,0),[events[1]]);
assert.deepEqual(c.step(400,0),[events[2]]);
assert.deepEqual(c.step(600,0),[events[3]]);assert(c.done);
c=new Clock(events,0);c.step(0,0);
assert.deepEqual(c.step(500,0),[events[1]]);assert.equal(c.recoveries,1);
assert.deepEqual(c.step(700,0),[events[2]]);
assert.deepEqual(c.step(900,0),[events[3]]);assert(c.done);
c=new Clock(events,0);c.step(0,0);
assert.deepEqual(c.step(200,12),[]);assert.deepEqual(c.step(400,12),[]);
assert.deepEqual(c.step(500,0),[]);assert.deepEqual(c.step(700,0),[events[1]]);
c=new Clock(events,0);c.step(0,0);c.step(1,12);
assert.throws(()=>c.step(3001,12),/3秒/);
c=new Clock(Array.from({length:100},(_,i)=>({at:0,hex:String(i)})),0);
let result=c.step(0,0);assert.equal(result.length,6);
assert.equal(c.step(1,11).length,1);assert.equal(c.step(2,12).length,0);
assert.equal(c.index,7);
console.log('PASS playback: normal timing, 300ms recovery preserves note-offs, bounded backlog, sustained-stall timeout, packet cap');
